import { readFile, readdir, cp, mkdir, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url),
  lock = JSON.parse(await readFile(new URL("package-lock.json", root), "utf8")),
  inventory = [];
await mkdir(new URL("dist/licenses/npm/", root), { recursive: true });
for (const [path, entry] of Object.entries(lock.packages)) {
  if (!path || entry.dev) continue;
  const dir = new URL(path + "/", root);
  let meta;
  try {
    meta = JSON.parse(await readFile(new URL("package.json", dir), "utf8"));
  } catch {
    continue;
  }
  const files = [];
  for (const item of await readdir(dir, { withFileTypes: true }))
    if (
      item.isFile() &&
      /^(licen[cs]e|notice|thirdparty|copying|copyright|authors)/i.test(
        item.name,
      )
    )
      files.push(item.name);
  const dest = new URL(
    "dist/licenses/npm/" + meta.name.replaceAll("/", "__") + "/",
    root,
  );
  await mkdir(dest, { recursive: true });
  for (const name of files) await cp(new URL(name, dir), new URL(name, dest));
  if (!files.length) {
    let text = "";
    if (meta.license === "MIT")
      ((text = (
        await readFile(
          new URL("public/licenses/onnxruntime-MIT.txt", root),
          "utf8",
        )
      ).split("Permission is hereby granted")[1]),
        (text = "Permission is hereby granted" + text));
    else if (meta.license === "ISC") {
      const isc = await readFile(
        new URL("node_modules/idb/LICENSE", root),
        "utf8",
      );
      text = isc.slice(isc.indexOf("Permission"));
    } else if (meta.license === "BSL")
      text = await readFile(
        new URL("public/licenses/Boost-1.0.txt", root),
        "utf8",
      );
    else if (meta.license === "Apache-2.0")
      text = await readFile(
        new URL("public/licenses/PaddleOCR-Apache-2.0.txt", root),
        "utf8",
      );
    if (!text) throw Error("Missing license text for " + meta.name);
    const notice =
      "Distribution notice generated by Canvas PDF because this npm archive omits a standalone license file.\n" +
      JSON.stringify(
        {
          name: meta.name,
          version: meta.version,
          license: meta.license,
          author: meta.author,
          repository: meta.repository,
        },
        null,
        2,
      ) +
      "\n\nThe original package metadata declares the license above; its source and copyright headers remain available in the pinned npm distribution. The standard permission text follows.\n\n" +
      text;
    await writeFile(new URL("DISTRIBUTION-NOTICE.txt", dest), notice);
    files.push("DISTRIBUTION-NOTICE.txt");
    if (meta.name === "clipper-lib") {
      const source = await readFile(new URL("clipper.js", dir), "utf8"),
        end = source.indexOf("*/");
      await writeFile(
        new URL("ORIGINAL-SOURCE-HEADER.txt", dest),
        source.slice(0, end + 2),
      );
      files.push("ORIGINAL-SOURCE-HEADER.txt");
    }
  }
  inventory.push({
    name: meta.name,
    version: meta.version,
    license: meta.license,
    repository: meta.repository,
    author: meta.author,
    files,
  });
}
await writeFile(
  new URL("dist/licenses/npm-inventory.json", root),
  JSON.stringify(inventory, null, 2),
);
await cp(
  new URL("../LICENSE", root),
  new URL("dist/licenses/shared-Apache-2.0.txt", root),
);
